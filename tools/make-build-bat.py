# -*- coding: utf-8 -*-
"""生成 native/build.bat —— 纯 ASCII + CRLF，自动探测 VS 安装位置"""
import io

L = []
a = L.append
a("@echo off")
a("setlocal enabledelayedexpansion")
a("set \"SRC=%~dp0src\"")
a("set \"OUT=%~dp0build\"")
a("set \"PF86=%ProgramFiles(x86)%\"")
a("")
a("rem ---------- locate vcvars64.bat ----------")
a("set \"VCVARS=\"")
a("set \"VSWHERE=!PF86!\\Microsoft Visual Studio\\Installer\\vswhere.exe\"")
a("if exist \"!VSWHERE!\" (")
a("  for /f \"usebackq tokens=*\" %%i in (`\"!VSWHERE!\" -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath`) do (")
a("    if exist \"%%i\\VC\\Auxiliary\\Build\\vcvars64.bat\" set \"VCVARS=%%i\\VC\\Auxiliary\\Build\\vcvars64.bat\"")
a("  )")
a(")")
a("if not defined VCVARS if exist \"!PF86!\\Microsoft Visual Studio\\2019\\BuildTools\\VC\\Auxiliary\\Build\\vcvars64.bat\" set \"VCVARS=!PF86!\\Microsoft Visual Studio\\2019\\BuildTools\\VC\\Auxiliary\\Build\\vcvars64.bat\"")
a("if not defined VCVARS if exist \"%ProgramFiles%\\Microsoft Visual Studio\\2022\\Community\\VC\\Auxiliary\\Build\\vcvars64.bat\" set \"VCVARS=%ProgramFiles%\\Microsoft Visual Studio\\2022\\Community\\VC\\Auxiliary\\Build\\vcvars64.bat\"")
a("if not defined VCVARS if exist \"%ProgramFiles%\\Microsoft Visual Studio\\2022\\BuildTools\\VC\\Auxiliary\\Build\\vcvars64.bat\" set \"VCVARS=%ProgramFiles%\\Microsoft Visual Studio\\2022\\BuildTools\\VC\\Auxiliary\\Build\\vcvars64.bat\"")
a("if not defined VCVARS goto novcvars")
a("")
a("echo [*] vcvars : !VCVARS!")
a("call \"!VCVARS!\" >nul 2>&1")
a("if errorlevel 1 goto novcvars")
a("if not exist \"!OUT!\" mkdir \"!OUT!\"")
a("if not exist \"!OUT!\\ui\" mkdir \"!OUT!\\ui\"")
a("if not exist \"!OUT!\\themes\" mkdir \"!OUT!\\themes\"")
a("")
a("echo [*] compile ...")
a("cl /nologo /std:c++17 /O2 /EHsc /W1 /utf-8 /D_UNICODE /DUNICODE /DWIN32_LEAN_AND_MEAN /DMG_ARCH=MG_ARCH_WIN32 /I\"!SRC!\" /I\"!SRC!\\vendor\" \"!SRC!\\main.cpp\" \"!SRC!\\vendor\\mongoose.c\" /Fe:\"!OUT!\\coolleo-svc.exe\" /Fo:\"!OUT!\\\\\" /link user32.lib shell32.lib shlwapi.lib gdi32.lib gdiplus.lib setupapi.lib hid.lib ws2_32.lib dwmapi.lib pdh.lib iphlpapi.lib ole32.lib oleaut32.lib d3d11.lib dxgi.lib advapi32.lib winhttp.lib")
a("if errorlevel 1 goto failed")
a("")
a("echo [*] copy ui ...")
a("copy /y \"%~dp0ui\\index.html\" \"!OUT!\\ui\\index.html\" >nul")
a("")
a("echo.")
a("echo [OK] !OUT!\\coolleo-svc.exe")
a("exit /b 0")
a("")
a(":novcvars")
a("echo [X] vcvars64.bat not found")
a("echo     install Visual Studio 2019/2022 with the C++ build tools")
a("echo     https://visualstudio.microsoft.com/visual-cpp-build-tools/")
a("exit /b 1")
a("")
a(":failed")
a("echo [X] build failed")
a("exit /b 1")

P = r"native/build.bat"
io.open(P, "w", encoding="ascii", newline="").write("\r\n".join(L) + "\r\n")
print("[OK] %s  %d 行  %d 字节" % (P, len(L), len(("\r\n".join(L) + "\r\n").encode("ascii"))))
